import React, { useMemo } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import useSWR from 'swr';
import { PieChart, Pie, Cell, Tooltip, ResponsiveContainer, Legend } from 'recharts';

// Fix 1: Explicitly point to backend port 5000
const API_BASE = 'http://localhost:5000';
const fetcher = (url) => fetch(url.startsWith('http') ? url : `${API_BASE}${url}`).then((r) => r.json());

export default function ZoneDetailsPage() {
    const { zoneId } = useParams();
    const navigate = useNavigate();

    // Fix 2: Request the modified backend /api/nilm/latest endpoint
    const { data: payload, isLoading, error } = useSWR('/api/nilm/latest', fetcher, {
        refreshInterval: 5000,
    });

    const currentZone = useMemo(() => {
        if (!payload?.zones) return null;
        return payload.zones[zoneId];
    }, [payload, zoneId]);

    if (isLoading) return <div className="p-8 text-center text-slate-500">Loading telemetry data...</div>;
    if (error || !currentZone) return <div className="p-8 text-center text-red-500">Zone data not found or offline.</div>;

    const kw = currentZone.value ?? 0;

    // Extract appliance breakdown data generated by the backend
    const appliances = currentZone.appliances || { HVAC: 0, Lighting: 0, Plug_Loads: 0 };

    const chartData = [
        { name: 'HVAC (Cooling/Air)', value: appliances.HVAC, color: '#3b82f6' },
        { name: 'Lighting', value: appliances.Lighting, color: '#f59e0b' },
        { name: 'Plug Loads (IT/Misc)', value: appliances.Plug_Loads, color: '#10b981' }
    ];

    return (
        <div className="min-h-screen bg-slate-50 p-6 flex flex-col items-center">
            <div className="w-full max-w-2xl">
                <div className="flex items-center gap-4 mb-6">
                    <button
                        onClick={() => navigate(-1)}
                        className="p-2 rounded-lg bg-white border border-slate-200 hover:bg-slate-100 text-slate-600 font-bold shadow-sm cursor-pointer"
                    >
                        ← Back
                    </button>
                    <div>
                        <h1 className="text-2xl font-extrabold text-slate-800">{currentZone.name || zoneId}</h1>
                        <p className="text-sm font-semibold text-slate-500 uppercase tracking-wide">
                            Appliance-Level Load Disaggregation
                        </p>
                    </div>
                </div>

                <div className="bg-white rounded-2xl shadow-sm border border-slate-200 p-6 mb-6">
                    <div className="flex justify-between items-center mb-6">
                        <div className="text-4xl font-black text-slate-800 font-mono">
                            {kw.toFixed(1)} <span className="text-lg text-slate-400">kW Total</span>
                        </div>
                        <span className="px-3 py-1 bg-emerald-100 text-emerald-800 font-bold text-xs rounded-full animate-pulse">
                            LIVE NILM
                        </span>
                    </div>

                    <div className="h-64 w-full">
                        <ResponsiveContainer width="100%" height="100%">
                            <PieChart>
                                <Pie
                                    data={chartData}
                                    cx="50%"
                                    cy="50%"
                                    innerRadius={70}
                                    outerRadius={100}
                                    paddingAngle={5}
                                    dataKey="value"
                                    stroke="none"
                                >
                                    {chartData.map((entry, index) => (
                                        <Cell key={`cell-${index}`} fill={entry.color} />
                                    ))}
                                </Pie>
                                <Tooltip
                                    formatter={(value) => [`${value.toFixed(1)} kW`, 'Power']}
                                    contentStyle={{ borderRadius: '8px', border: 'none', boxShadow: '0 4px 12px rgba(0,0,0,0.1)', fontWeight: 'bold' }}
                                />
                                <Legend verticalAlign="bottom" height={36} wrapperStyle={{ fontSize: '12px', fontWeight: 600 }} />
                            </PieChart>
                        </ResponsiveContainer>
                    </div>
                </div>

                <div className="grid grid-cols-1 gap-3">
                    {chartData.map((item, idx) => {
                        const pct = kw > 0 ? (item.value / kw) * 100 : 0;
                        return (
                            <div key={idx} className="bg-white p-4 rounded-xl border border-slate-200 flex items-center justify-between shadow-sm">
                                <div className="flex items-center gap-3">
                                    <div className="w-3 h-3 rounded-full" style={{ backgroundColor: item.color }}></div>
                                    <span className="font-bold text-slate-700">{item.name}</span>
                                </div>
                                <div className="text-right">
                                    <div className="text-lg font-black text-slate-800 font-mono">{item.value.toFixed(1)} kW</div>
                                    <div className="text-xs font-bold text-slate-400">{pct.toFixed(1)}% of zone</div>
                                </div>
                            </div>
                        );
                    })}
                </div>
            </div>
        </div>
    );
}