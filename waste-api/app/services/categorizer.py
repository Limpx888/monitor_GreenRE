def get_class_config(class_name: str) -> dict:
    """Get default config for a waste class."""
    return DEFAULT_CLASS_MAP.get(class_name, {
        "category": "REVIEW",
        "material": "unknown",
        "avg_weight_kg": 0.05,
        "emission_factor_kgco2e": 1.0,
        "recyclable_locally": False,
        "tip_reduce": "Review this item to determine the best disposal method.",
        "tip_reuse": "Check if this item can be repurposed before disposal.",
        "tip_recycle": "Check local recycling guidelines for this item type.",
    })


def get_tip_for_detection(class_name: str, category: str) -> str:
    """Get the primary tip to show right after a scan."""
    config = get_class_config(class_name)
    if category == "RECYCLE":
        return config.get("tip_recycle", "Check local recycling guidelines.")
    elif category == "ORGANIC":
        return config.get("tip_recycle", "Compost this item if possible.")
    elif category == "HAZARDOUS":
        return config.get("tip_recycle", "Handle with care. Take to a proper disposal facility.")
    elif category == "REDUCE":
        return config.get("tip_reduce", "Consider reducing use of this item.")
    else:
        return config.get("tip_recycle", "Dispose properly in the correct bin.")
